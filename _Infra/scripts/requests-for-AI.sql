 
-- Запрос 1: количество измерений по пользователям
 
select t1."Код", t1."Фамилия", count(t3."Код") as measurement_count
from "Пользователи" t1
left join "Пачки" t2 on t1."Код" = t2."Код пользователя"
left join "Параметры" t3 on t2."Код" = t3."Код пачки"
group by t1."Код", t1."Фамилия";
 
 
-- Запрос 2: проверка пустых пачек
 
select t1."Код" as batch_id, count(t2."Код") as param_count
from "Пачки" t1
left join "Параметры" t2 on t1."Код" = t2."Код пачки"
group by t1."Код"
having count(t2."Код") = 0;
 
 
-- Запрос 3: проверка количества параметров в пачке (включая пачки без параметров)
 
select t1."Код" as batch_id, count(t2."Код") as param_count
from "Пачки" t1
left join "Параметры" t2 on t1."Код" = t2."Код пачки"
group by t1."Код"
having count(t2."Код") != 5;
 
 
-- Запрос 4: проверка значений вне диапазона (включая параметры без типа)
 
select t1.* from "Параметры" t1
left join "Типы параметров" t2 on t1."Код типа параметра" = t2."Код"
where t2."Код" is null
   or (t2."Мин значение" is not null and cast(t1."Значение" as numeric) < t2."Мин значение")
   or (t2."Макс значение" is not null and cast(t1."Значение" as numeric) > t2."Макс значение");
 
 
-- Запрос 5: проверка единицы измерения и диапазона по жёстко заданным значениям
 
