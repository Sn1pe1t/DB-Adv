-- Константы для расчёта Метео приближенный
-- Структура и данные

begin;

do 
$$ begin

    drop table if exists "Константы" cascade;
    drop sequence if exists seq_constants;

    create sequence seq_constants;

    create table "Константы" (
        "Код"      integer       primary key default nextval('seq_constants'),
        "Название" varchar(100)  not null unique,
        "Значение" numeric       not null,
        "Описание" varchar(200)
    );

    insert into "Константы" ("Код", "Название", "Значение", "Описание") values
        (1, 'Табличное давление',                 750,  'мм рт. ст.'),
        (2, 'Табличная виртуальная температура',  15.9, 'градусы Цельсия'),
        (3, 'Смещение отрицательного давления',   500,  'для записи БББ при отрицательном отклонении (-7 -> 507)'),
        (4, 'Смещение отрицательной температуры', 50,   'для записи ТТ при отрицательном отклонении (-12 -> 62)'),
        (5, 'Виртуальная поправка ниже 0',        0,    'таблица 1 ТЗ, столбец "Ниже 0"'),
        (6, 'По умолчанию: высота метеопоста',    100,  'м'),
        (7, 'По умолчанию: температура',          15,   'градусы Цельсия'),
        (8, 'По умолчанию: давление',             750,  'мм рт. ст.'),
        (9, 'По умолчанию: направление ветра',    0,    'записывается как 00'),
        (10, 'По умолчанию: скорость ветра',      0,    'м/с'),
        (11, 'По умолчанию: дальность сноса пуль', 0,   'м');

    perform setval('seq_constants', (select max("Код") from "Константы"));

end $$;

commit;


-- Функция: значение константы по названию

CREATE OR REPLACE FUNCTION public."Константа"(p_name text)
    RETURNS numeric
    LANGUAGE 'sql'
    STABLE
AS $BODY$
	select "Значение" from "Константы" where "Название" = p_name
$BODY$;


