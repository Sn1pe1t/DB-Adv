-- Перенос и связывание существующих данных (DML)
 

UPDATE "Параметры"
SET "Код пачки" = (
    SELECT p."Код"
    FROM "Пачки" p
    WHERE p."Код параметра" = "Параметры"."Код"
    LIMIT 1
);
 
UPDATE "Параметры"
SET "Код типа параметра" = (
    SELECT tp."Код"
    FROM "Типы параметров" tp
    WHERE tp."Название" = "Параметры"."Название"
);
 
 
-- Удаление лишнего (DDL)
 
 
ALTER TABLE "Пачки" DROP COLUMN "Код параметра";
 
 
-- Итоговый запрос
 
 
SELECT
    p."Дата измерения"                          AS "Дата измерения",
    p."Код"                                      AS "Номер пачки",
    u."Фамилия" || ' ' || u."Имя"                AS "ФИО сотрудника",
    tp."Название" || ' (' || eu."Символ" || ')'  AS "Параметр и ед. измерения",
    par."Значение"                               AS "Значение"
FROM "Пачки" p
JOIN "Пользователи"      u  ON p."Код пользователя"    = u."Код"
JOIN "Параметры"         par ON par."Код пачки"        = p."Код"
JOIN "Типы параметров"   tp  ON par."Код типа параметра" = tp."Код"
JOIN "Единицы измерения" eu  ON tp."Код единицы измерения" = eu."Код"
ORDER BY p."Дата измерения";